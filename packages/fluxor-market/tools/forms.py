"""Meta-skill forms: the checks `marketplace.py validate` runs on a `form.json`, and its Markdown rendering.

A form is data (`schemas/form.schema.json`): modules, sections and questions with stable ids, and
for each question the profile slots its answer feeds. With the profile and the templates it gives
three checks, which together make the coverage of a generative meta-skill:

- every slot the profile declares is **fed** by at least one question (or is `derived` from the
  whole interview, or is a header slot filled at synthesis);
- every question **feeds** at least one slot or **captures** decisions;
- every slot is **rendered** by at least one artifact template, or is marked `profileOnly`.

`questions.md` next to `form.json` is a rendering of it for people, generated by
`marketplace.py forms` and checked to be up to date, so the form has one source.

Standard library only (Python 3.9+).
"""

from __future__ import annotations

import json
from pathlib import Path

# Header slots every profile has (the pack contract's `{meta.*}`): filled by the renderer.
HEADER_PREFIX = "meta."
GENERATED_NOTE = ("<!-- Generated from form.json by `python3 tools/marketplace.py forms`. "
                  "Edit form.json, then regenerate. -->")


def load(path: Path) -> tuple[dict | None, list[str]]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return None, [f"not valid JSON ({exc})"]
    if not isinstance(data, dict):
        return None, ["a form is a JSON object"]
    return data, []


def questions(form: dict) -> list[tuple[dict, dict, dict]]:
    """(module, section, question) in interview order."""
    out = []
    for module in form.get("modules", []):
        for section in module.get("sections", []):
            for question in section.get("questions", []):
                out.append((module, section, question))
    return out


def structure_findings(form: dict, role_id: str) -> list[str]:
    """What the schema cannot say: unique ids, and the form names its own meta-skill."""
    errors = []
    if form.get("role") != role_id:
        errors.append(f"role {form.get('role')!r} must be {role_id!r}")
    for label, ids in (("module", [m.get("id") for m in form.get("modules", [])]),
                       ("section", [s.get("id") for m in form.get("modules", []) for s in m.get("sections", [])]),
                       ("question", [q.get("id") for _, _, q in questions(form)])):
        seen = set()
        for value in ids:
            if value in seen:
                errors.append(f"duplicate {label} id {value!r}")
            seen.add(value)
    return errors


def coverage_findings(form: dict, declared: set[str], used: set[str]) -> list[str]:
    """Fed, feeding and rendered, as described in the module docstring. `declared` are the
    profile's slots; `used` are the slots the artifact templates (not the profile) use."""
    errors = []
    name_slot = form.get("nameSlot")
    derived = form.get("derived", {})
    profile_only = form.get("profileOnly", {})
    if name_slot and name_slot not in declared:
        errors.append(f"nameSlot {name_slot!r} is not declared by the profile")
    for label, marked in (("derived", derived), ("profileOnly", profile_only)):
        for slot in sorted(set(marked) - declared):
            errors.append(f"{label} names {{{slot}}}, which the profile does not declare")
    for slot in sorted(set(profile_only) & used):
        errors.append(f"profileOnly names {{{slot}}}, but a template renders it: remove the marker")

    fed: set[str] = set()
    for _, section, question in questions(form):
        feeds = question.get("feeds", [])
        for slot in feeds:
            if slot not in declared:
                errors.append(f"{question.get('id')} feeds {{{slot}}}, which the profile does not declare")
        if not feeds and not question.get("captures"):
            errors.append(f"{question.get('id')} feeds no slot and captures nothing")
        fed.update(feeds)

    content = {s for s in declared if not s.startswith(HEADER_PREFIX) and s != name_slot}
    for slot in sorted(content - fed - set(derived)):
        errors.append(f"no question feeds {{{slot}}}")
    for slot in sorted(content - used - set(profile_only)):
        errors.append(f"no template renders {{{slot}}}: use it in an artifact or mark it profileOnly")
    return errors


def minutes(items) -> int:
    return sum(q.get("minutes", 0) for q in items)


def render_markdown(form: dict) -> str:
    """The form for people: one heading per module and section, one entry per question."""
    lines = [f"# Interview — {form.get('title', form.get('role', ''))}", "", GENERATED_NOTE, ""]
    if form.get("intro"):
        lines += [form["intro"], ""]
    lines += ["| Module | Questions | Minutes, required questions | Minutes, all | |",
              "| --- | --- | --- | --- | --- |"]
    for module in form.get("modules", []):
        items = [q for s in module.get("sections", []) for q in s.get("questions", [])]
        required = [q for q in items if q.get("required") and not module.get("optional")]
        needed = f"~{minutes(required)}" if not module.get("optional") else "—"
        lines.append(f"| {module.get('title')} | {len(items)} | {needed} | ~{minutes(items)} | "
                     f"{'optional' if module.get('optional') else 'required'} |")
    lines.append("")
    for module in form.get("modules", []):
        suffix = " (optional)" if module.get("optional") else ""
        lines += [f"## {module.get('title')}{suffix}", "", module.get("purpose", ""), ""]
        for section in module.get("sections", []):
            lines += [f"### {section.get('id')}. {section.get('title')}", ""]
            for q in section.get("questions", []):
                tags = [f"~{q.get('minutes')} min"]
                if q.get("kind", "open") != "open":
                    tags.append(q["kind"])
                if not q.get("required"):
                    tags.append("optional")
                if q.get("captures"):
                    tags.append("captures " + ", ".join(q["captures"]))
                lines.append(f"**{q.get('id')}.** {q.get('prompt')}")
                lines.append("")
                meta = " · ".join(tags)
                if q.get("feeds"):
                    meta += " · feeds " + ", ".join(f"`{s}`" for s in q["feeds"])
                lines.append(f"<sub>{meta}</sub>")
                lines.append("")
                for probe in q.get("probes", []):
                    lines.append(f"- Probe: {probe}")
                if q.get("probes"):
                    lines.append("")
    if form.get("wrap"):
        lines += ["---", "", f"*{form['wrap']}*", ""]
    return "\n".join(lines).rstrip("\n") + "\n"
